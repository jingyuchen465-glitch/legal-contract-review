test('saving retains native markup, preserves the original and rejects stale concurrent writes', async () => {
  const endpoint = `/api/contracts/${fixture.contract.id}/review-document`;
  const opened = await legal.get(`${endpoint}?reviewId=${fixture.reviewId}`).buffer(true).parse(bytes).expect(200);
  const modified = applyClauseRevisions(opened.body, { explanation: '明确履行期限', edits: [{ operation: 'replace', blockId: 'b1', originalText: '交付期限另行商议。', newText: '交付期限明确为30日。' }] }, '法务测试', '2026-11-11T03:21:00.000Z');
  await submitter.post(endpoint).set('X-CSRF-Token', submitterCsrf).field('baseVersionId', fixture.version.id).attach('file', modified, '审阅.docx').expect(403);
  await legal.post(endpoint).set('X-CSRF-Token', csrf).field('baseVersionId', fixture.version.id).attach('file', Buffer.from('invalid'), '审阅.docx').expect(422);
  const saved = await legal.post(endpoint).set('X-CSRF-Token', csrf).field('baseVersionId', fixture.version.id).attach('file', modified, '审阅.docx').expect(200);
  assert.equal(saved.body.versionNo, 2);
  const current = await db('la_contracts').where({ id: fixture.contract.id }).first();
  assert.equal(current.current_version_id, saved.body.versionId);
  const stored = await db('la_versions').where({ id: saved.body.versionId }).first();
  assert.equal(stored.source_action, 'margin_review');
  assert.deepEqual(await storage.read(stored.storage_key), modified);
  assert.deepEqual(await storage.read(fixture.version.storage_key), original);
  const reopened = await legal.get(endpoint).buffer(true).parse(bytes).expect(200);
  const zip = new AdmZip(reopened.body);
  assert.match(zip.readAsText('word/document.xml'), /<w:ins\b/);
  assert.match(zip.readAsText('word/document.xml'), /<w:del\b/);
  assert.match(zip.readAsText('word/comments.xml'), /明确为30日/);
  await legal.post(endpoint).set('X-CSRF-Token', csrf).field('baseVersionId', fixture.version.id).attach('file', modified, '审阅.docx').expect(409);
  assert.equal((await db('la_versions').where({ contract_id: fixture.contract.id }).count('* as n').first()).n, '2');
  const audit = await db('la_audit').where({ action: 'document.margin_review_save', entity_id: fixture.contract.id }).first();
  assert.ok(audit);
});
