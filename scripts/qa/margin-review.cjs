const { chromium } = require('C:/Users/Administrator/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const AdmZip = require('adm-zip');
const { parseDocx } = require('../../backend/pilot/parser');
const output = '.local/margin-review';
async function main() {
  const browser = await chromium.launch({ channel: 'msedge' });
  const context = await browser.newContext({ viewport: { width: 1500, height: 1000 }, acceptDownloads: true });
  const page = await context.newPage(), errors = [], checks = [];
  page.on('pageerror', error => errors.push(error.message));
  async function open() {
    if (page.url().includes('/#/review-preview')) await page.reload();
    else await page.goto('http://localhost:8080/#/review-preview');
    await page.waitForFunction(() => document.querySelectorAll('.review-margin-card').length >= 5);
    await page.waitForTimeout(500);
  }
  async function download(name) {
    const event = page.waitForEvent('download');
    await page.getByRole('button', { name: '导出 DOCX', exact: true }).click();
    const file = await event; await file.saveAs(`${output}/${name}.docx`);
    return fs.readFileSync(`${output}/${name}.docx`);
  }
  try {
    await open();
    assert.equal(await page.locator('.review-margin-card.comment').count(), 10);
    assert.equal(await page.locator('.review-margin-card.change').count(), 2);
    const initial = new AdmZip(await download('export-initial'));
    assert.equal((initial.readAsText('word/document.xml').match(/<w:ins\b/g) || []).length, 2);
    assert.equal((initial.readAsText('word/document.xml').match(/<w:del\b/g) || []).length, 2);
    assert.equal((initial.readAsText('word/comments.xml').match(/<w:comment\b/g) || []).length, 10);
    checks.push('原生批注与两组替换修订导出保留');
    const filters = page.locator('.margin-summary-filters');
    await filters.getByRole('button', { name: /^已处理/ }).click();
    await page.getByText('暂无已处理批注', { exact: true }).waitFor();
    await filters.getByRole('button', { name: /^全部/ }).click();
    const thread = page.locator('.review-margin-card.comment').first();
    const threadId = await thread.getAttribute('data-review-id');
    const card = () => page.locator(`.review-margin-card.comment[data-review-id="${threadId}"]`);
    const originalText = await card().locator('.review-margin-body').textContent();
    await card().getByRole('button', { name: '标记为已处理', exact: true }).click();
    await page.waitForFunction(id => document.querySelector(`[data-review-id="${id}"]`)?.dataset.commentStatus === 'resolved', threadId);
    assert.equal(await page.locator('.review-margin-card.comment').count(), 10);
    assert.equal(await card().locator('.review-margin-body').textContent(), originalText);
    assert.match(await filters.getByRole('button', { name: /^已处理/ }).textContent(), /1/);
    assert.match(await page.locator('.margin-file-group p').textContent(), /有修改待保存/);
    const resolved = new AdmZip(await download('export-resolved'));
    assert.equal(resolved.readAsText('word/document.xml'), initial.readAsText('word/document.xml'));
    assert.equal((resolved.readAsText('word/comments.xml').match(/<w:comment\b/g) || []).length, 10);
    assert.match(resolved.readAsText('word/commentsExtended.xml'), /(?:w15:)?done="1"/);
    await filters.getByRole('button', { name: /^已处理/ }).click();
    await page.waitForFunction(() => document.querySelectorAll('.review-margin-card.comment').length === 1);
    assert.equal(await page.locator('.review-margin-card.comment').count(), 1);
    await page.getByRole('button', { name: '保存到本机', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.margin-file-group p').textContent.includes('已保存到本机'));
    await open();
    assert.equal(await page.locator('.review-margin-card.comment.resolved').count(), 1);
    assert.equal(await page.locator('.review-margin-card.comment').count(), 10);
    await filters.getByRole('button', { name: /^已处理/ }).click();
    await page.getByRole('button', { name: '重新打开', exact: true }).click();
    await page.getByText('暂无已处理批注', { exact: true }).waitFor();
    await page.getByRole('button', { name: '查看全部批注', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.review-margin-card.comment').length === 10);
    assert.equal(await page.locator('.review-margin-card.comment.resolved').count(), 0);
    await page.getByRole('button', { name: '保存到本机', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.margin-file-group p').textContent.includes('已保存到本机'));
    await open();
    assert.equal(await page.locator('.review-margin-card.comment.resolved').count(), 0);
    const reopened = new AdmZip(await download('export-reopened'));
    assert.equal(reopened.readAsText('word/document.xml'), initial.readAsText('word/document.xml'));
    assert.ok(!/(?:w15:)?done="1"/.test(reopened.readAsText('word/commentsExtended.xml')));
    checks.push('处理后卡片保留、筛选与重新打开正常，状态经 DOCX 保存重载保留且正文修订不变');
    await page.locator('.margin-stage').evaluate(e => { e.scrollTop = 260; });
    await page.waitForTimeout(350);
    await page.screenshot({ path: `${output}/review-workspace.png` });
    const before = await page.locator('.review-margin-card.change').first().boundingBox();
    await page.locator('.margin-stage').evaluate(e => { e.scrollTop += 120; });
    await page.waitForTimeout(350);
    const after = await page.locator('.review-margin-card.change').first().boundingBox();
    assert.ok(Math.abs(before.y - after.y - 120) < 2);
    await page.locator('.margin-zoom select').selectOption('80');
    await page.waitForTimeout(600);
    assert.equal(await page.locator('.review-margin-card.change').count(), 2);
    checks.push('滚动和缩放后页边卡片仍绑定实际正文');
    await page.locator('.margin-zoom select').selectOption('100');
    await page.waitForTimeout(400);
    await page.getByRole('button', { name: '接受此处修订', exact: true }).first().click();
    await page.waitForFunction(() => document.querySelectorAll('.review-margin-card.change').length === 1);
    await page.getByRole('button', { name: '拒绝此处修订', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.review-margin-card.change').length === 0);
    const decided = new AdmZip(await download('export-decided'));
    const xml = decided.readAsText('word/document.xml');
    assert.equal((xml.match(/<w:(?:ins|del)\b/g) || []).length, 0);
    const parsed = parseDocx(decided.toBuffer());
    const text = parsed.blocks.map(b => b.text).join('\n');
    assert.ok(text.includes('乙方迁仓前应取得甲方书面同意'));
    assert.ok(text.includes('甲方在3日内未提出异议的视为认可'));
    assert.ok(!text.includes('甲方自收悉后10个工作日内核对'));
    checks.push('接受及拒绝确实修改 OOXML 正文并移除对应修订');
    await page.getByRole('button', { name: '保存到本机', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.margin-file-group p').textContent.includes('已保存到本机'));
    await open();
    assert.equal(await page.locator('.review-margin-card.change').count(), 0);
    assert.match(await page.locator('.margin-file-group p').textContent(), /已恢复本机保存/);
    checks.push('保存到 IndexedDB 后重载恢复实际 DOCX');
    // Select using the actual editor keyboard surface, then move into the composer.
    await page.locator('.ts-para').nth(3).click();
    await page.keyboard.press('Home');
    await page.keyboard.press('Shift+End');
    await page.waitForFunction(() => !document.querySelector('.margin-review').__vueParentComponent.exposed.getEditor().ui.selection.getSnapshot().empty);
    await page.getByRole('button', { name: '添加批注', exact: true }).click();
    await page.getByRole('textbox', { name: '批注内容' }).fill('本地验收：请补充完整的签约主体信息。');
    await page.getByRole('button', { name: '保存批注', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.review-margin-card.comment').length === 11);
    const commentZip = new AdmZip(await download('export-new-comment'));
    assert.match(commentZip.readAsText('word/comments.xml'), /本地验收：请补充完整的签约主体信息/);
    checks.push('选区新增批注写入 DOCX comments.xml');
    await page.locator('.review-margin-card.comment').first().getByRole('button', { name: '回复', exact: true }).click();
    await page.getByRole('textbox', { name: '批注内容' }).fill('验收回复：主体信息待业务补充。');
    await page.getByRole('button', { name: '保存批注', exact: true }).click();
    await page.waitForFunction(() => !document.querySelector('.review-comment-composer'));
    const replied = new AdmZip(await download('export-reply'));
    assert.match(replied.readAsText('word/comments.xml'), /验收回复：主体信息待业务补充/);
    checks.push('回复批注保留在导出的原生评论中');
    await page.locator('.review-margin-card.comment').first().getByRole('button', { name: '标记为已处理', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.review-margin-card.comment.resolved').length === 1);
    const resolvedReply = new AdmZip(await download('export-resolved-reply'));
    assert.match(resolvedReply.readAsText('word/comments.xml'), /验收回复：主体信息待业务补充/);
    await page.locator('.review-margin-card.comment.resolved').getByRole('button', { name: '重新打开', exact: true }).click();
    await page.waitForFunction(() => !document.querySelector('.review-margin-card.comment.resolved'));
    await page.getByRole('button', { name: '关闭批注状态提示', exact: true }).click();
    await page.evaluate(() => {
      const api = document.querySelector('.margin-review').__vueParentComponent.exposed.getEditor().ui.comments;
      window.marginResolve = api.resolve; api.resolve = async () => ({ success: false, message: '模拟处理失败' });
    });
    await page.locator('.review-margin-card.comment').first().getByRole('button', { name: '标记为已处理', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: '模拟处理失败' }).waitFor();
    assert.equal(await page.locator('.review-margin-card.comment.resolved').count(), 0);
    assert.equal(await page.locator('.margin-comment-feedback').count(), 0);
    await page.evaluate(() => { document.querySelector('.margin-review').__vueParentComponent.exposed.getEditor().ui.comments.resolve = window.marginResolve; delete window.marginResolve; });
    await page.getByRole('button', { name: '关闭错误提示', exact: true }).click();
    checks.push('已处理批注保留回复，操作失败显示错误且不误报成功');
    await page.locator('.ts-para').nth(4).click();
    await page.keyboard.press('End');
    await page.keyboard.type('本地验收新增文字');
    await page.waitForFunction(() => document.querySelectorAll('.review-margin-card.change').length > 0);
    const typed = new AdmZip(await download('export-typed'));
    assert.match(typed.readAsText('word/document.xml'), /<w:ins\b[^>]*w:author="法务审阅人"/);
    assert.match(typed.readAsText('word/document.xml'), /本地验收新增文字/);
    await page.getByTitle('撤销', { exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.review-margin-card.change').length === 0);
    checks.push('实际键盘编辑生成署名原生修订，撤销恢复正文');
    await page.evaluate(() => { window.marginOriginalPut = IDBObjectStore.prototype.put; IDBObjectStore.prototype.put = function () { throw new Error('模拟本机存储写入失败'); }; });
    await page.getByRole('button', { name: '保存到本机', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.margin-error')?.textContent.includes('模拟本机存储写入失败'));
    assert.match(await page.locator('.margin-file-group p').textContent(), /有修改待保存/);
    assert.equal(await page.locator('.review-margin-card.comment').count(), 11);
    await page.evaluate(() => { IDBObjectStore.prototype.put = window.marginOriginalPut; delete window.marginOriginalPut; });
    await page.getByRole('button', { name: '关闭错误提示', exact: true }).click();
    checks.push('保存失败保留文档和未保存状态');
    await page.locator('.margin-display select').selectOption('final');
    await page.waitForTimeout(300);
    assert.equal(await page.locator('.review-margin-card').count(), 0);
    await page.locator('.margin-display select').selectOption('markup');
    await page.waitForFunction(() => document.querySelectorAll('.review-margin-card').length > 0);
    checks.push('正文对照视图及修订视图切换');
    assert.deepEqual(errors, []);
    fs.writeFileSync(`${output}/browser-checks.json`, JSON.stringify({ checks, errors }, null, 2));
    console.log(JSON.stringify({ checks, errors }, null, 2));
  } finally { await context.close(); await browser.close(); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });

